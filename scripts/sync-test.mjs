import { chromium } from '@playwright/test'
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } })
const errors = []
const watch = (p) => { p.on('pageerror', (e) => errors.push(e.message)); p.on('console', (m) => m.type() === 'error' && errors.push(m.text())) }
const ws = await ctx.newPage(); watch(ws)
await ws.goto('http://localhost:5173/e/evt-cbe/match-day', { waitUntil: 'networkidle' })
await ws.evaluate(() => localStorage.clear()); await ws.reload({ waitUntil: 'networkidle' })
const tv = await ctx.newPage(); watch(tv)
await tv.setViewportSize({ width: 1920, height: 1080 })
await tv.goto('http://localhost:5173/tv/evt-cbe/1', { waitUntil: 'networkidle' })
const um = await ctx.newPage(); watch(um)
await um.setViewportSize({ width: 390, height: 844 })
await um.goto('http://localhost:5173/u/evt-cbe-c1', { waitUntil: 'networkidle' })
await um.getByRole('button', { name: /I am/ }).click()
await um.getByRole('button', { name: /LIVE, tap to continue/ }).click()
await um.waitForTimeout(500)
await um.screenshot({ path: 'screenshots/phase-08/umpire-pad-390.png' })
const pad = um.getByRole('button', { name: /Point to/ }).first()
for (let i = 0; i < 3; i++) { await pad.click(); await um.waitForTimeout(150) }
await um.waitForTimeout(800)
await um.screenshot({ path: 'screenshots/phase-08/umpire-after-390.png' })
await ws.bringToFront(); await ws.waitForTimeout(800)
const wsText = await ws.locator('main').innerText()
await ws.screenshot({ path: 'screenshots/phase-08/matchday-1440.png' })
await tv.bringToFront(); await tv.waitForTimeout(800)
await tv.screenshot({ path: 'screenshots/phase-08/tv-court1-1920.png' })
console.log('workspace mentions 9-4?', /9\s*\n?.*4/.test(wsText))
await tv.goto('http://localhost:5173/tv/evt-cbe/all', { waitUntil: 'networkidle' }); await tv.waitForTimeout(800)
await tv.screenshot({ path: 'screenshots/phase-08/tv-all-1920.png' })
console.log(errors.length ? errors.join('\n') : 'no errors')
await b.close()
